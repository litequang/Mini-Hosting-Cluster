import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
const root=process.argv[2];assert.ok(root);
const home=fs.mkdtempSync(path.join(os.tmpdir(),'mhc-manual-test-'));
const cfg=path.join(home,'.config/mhc-full-installer');fs.mkdirSync(cfg,{recursive:true,mode:0o700});
const put=(p,v)=>fs.writeFileSync(path.join(cfg,p),JSON.stringify(v),{mode:0o600});
const ctrl='11111111-1111-4111-8111-111111111111',peer='22222222-2222-4222-8222-222222222222';
put('node-identity.json',{nodeId:ctrl});put('cluster.json',{controllerNodeId:ctrl,clusterId:'99999999-9999-4999-8999-999999999999',mode:'inventory-only'});
put('members.json',{nodes:[{nodeId:ctrl,label:'LAB controller',verification:'local-controller'},{nodeId:peer,label:'LAB peer',verification:'ssh-authenticated-pairing-only',lastSeenAt:new Date().toISOString()}]});
const run=(...args)=>spawnSync(process.execPath,[path.join(root,'bin/manual-primary.mjs'),...args],{env:{...process.env,HOME:home},encoding:'utf8',timeout:4000});
let checks=0;const expect=(fn)=>{fn();checks++;};
expect(()=>assert.equal(run('status').status,0));expect(()=>assert.equal(run('plan',peer).status,0));
expect(()=>assert.equal(run('begin',peer).status,1));
expect(()=>assert.equal(run('begin',peer,'--confirm=PREPARE_MANUAL_PRIMARY').status,0));
expect(()=>assert.equal(run('begin',peer,'--confirm=PREPARE_MANUAL_PRIMARY').status,1));
const pending=JSON.parse(run('status').stdout).pending;expect(()=>assert.ok(pending.operationId));
expect(()=>assert.equal(run('complete',pending.operationId,'--confirm=RECORD_OPERATOR_SELECTED_PRIMARY').status,1));
expect(()=>assert.equal(run('complete',pending.operationId,'--confirm=RECORD_OPERATOR_SELECTED_PRIMARY','--backup-restored','--old-writes-stopped','--target-tested','--routing-switched').status,0));
expect(()=>assert.equal(JSON.parse(run('status').stdout).declaredPrimary.nodeId,peer));
expect(()=>assert.equal(run('begin',peer,'--confirm=PREPARE_MANUAL_PRIMARY').status,1));
fs.rmSync(home,{recursive:true,force:true});console.log(`PASS: ${checks} manual-primary assertions`);
