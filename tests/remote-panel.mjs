 const cli=path.join(root,'bin/remote-panel.mjs');
 const run=(args)=>spawnSync(process.execPath,[cli,...args],{encoding:'utf8',env:{...process.env,HOME:home}});
 ok(run(['plan']).status===0,'plan no remote changes');
 ok(run(['configure','evil/host','mhctest.cloudflareaccess.com','a'.repeat(64),'--confirm=ENABLE_CLOUDFLARE_ACCESS_JWT']).status!==0,'bad hostname');
 ok(run(['configure','admin.thophuong.com','not-cloudflare.com','a'.repeat(64),'--confirm=ENABLE_CLOUDFLARE_ACCESS_JWT']).status!==0,'bad team');
 ok(run(['configure','admin.thophuong.com','mhctest.cloudflareaccess.com','a'.repeat(64),'--confirm=ENABLE_CLOUDFLARE_ACCESS_JWT']).status===0,'configure requires explicit consent');
 ok((fs.statSync(path.join(data,'remote-access.json')).mode&0o077)===0,'private config');
 ok(run(['configure','panel.thophuong.com','mhctest.cloudflareaccess.com','a'.repeat(64),'--confirm=ENABLE_CLOUDFLARE_ACCESS_JWT']).status!==0,'no silent overwrite');
 const c=config();ok(c.hostname==='admin.thophuong.com','configured correct hostname');
 ok(publicStatus().remoteHostname===c.hostname,'public status no secrets');
 const pair=crypto.generateKeyPairSync('rsa',{modulusLength:2048});
