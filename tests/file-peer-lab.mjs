import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
const root=path.resolve(process.argv[2]||'.');
const cli=path.join(root,'bin/file-peer-lab.mjs'),delta=path.join(root,'bin/file-delta-lab.mjs');
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'mhc-c2-peer-'));
const srcHome=path.join(tmp,'sourcehome'),dstHome=path.join(tmp,'receiverhome'),mock=path.join(tmp,'mockbin');
