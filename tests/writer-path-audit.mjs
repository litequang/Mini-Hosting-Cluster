import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {pathToFileURL} from 'node:url';
const root=process.argv[2];
const {SURFACES,RELEASE,analyzeWritePaths,observeLocalSignals}=await import(pathToFileURL(path.join(root,'bin/writer-path-audit.mjs')).href);
let n=0;const ok=(cond,msg)=>{assert.ok(cond,msg);n++;};
const item=(r,k)=>r.paths.find(x=>x.id===k);
const base=analyzeWritePaths();
ok(base.scope==='LOCAL_READ_ONLY_HOST_WRITE_PATH_INVENTORY','read only scope');
ok(base.pathCount===12,'all write surfaces');
ok(base.unverifiedFencingPaths===12,'nothing trusted by default');
ok(base.paths.every(p=>p.fenceStatus==='NOT_ATTESTED'&&p.canBypassGate==='NOT_EXCLUDED'&&!p.safeToWrite),'unknown remains nonfenced');
ok(!base.readiness.canSwitchPrimary&&!base.readiness.canArmHA,'can never authorize');
ok(base.activeOrConfiguredCount===0,'no evidence default');
const all=analyzeWritePaths({signals:{termuxEnv:true,siteRegistration:true,cloudflaredConfig:true,tpEnv:true},services:{nginx:'running',mysqld:'running','amh-panel':'running','sshd':'running','mhc-full-wp-php':'running','named-tunnel':'running','crond':'running'}});
ok(all.activeOrConfiguredCount>=10,'active writers seen');
ok(item(all,'mariadb_direct').observation==='RUNNING_SERVICE','SQL socket writers active');
ok(item(all,'php_wordpress').observation==='RUNNING_SERVICE','php writer active');
ok(item(all,'cloudflare_route').observation==='RUNNING_SERVICE','route active');
ok(item(all,'shell_ssh').observation==='RUNNING_SERVICE','ssh active');
ok(item(all,'external_writers').observation==='CONFIG_PRESENT','outside known writers remain');
ok(all.unverifiedFencingPaths===12,'even running writers not fenced');
ok(!all.readiness.productionWriteProtectionVerified,'cannot claim protection');
ok(all.paths.every(x=>x.fenceStatus==='NOT_ATTESTED'),'no unsafe inference');
const stopped=analyzeWritePaths({services:{mysqld:'stopped',nginx:'stopped','sshd':'stopped'}});
ok(item(stopped,'mariadb_direct').observation==='NOT_OBSERVED','stopped not running');
ok(item(stopped,'mariadb_direct').fenceStatus==='NOT_ATTESTED','stopped is not fencing');
ok(!stopped.readiness.canSwitchPrimary,'not safe if all services stopped');
const malicious=analyzeWritePaths({signals:{termuxEnv:true,password:'SUPER_SECRET',siteRegistration:'yes'},services:{mysqld:'RUNNING',nginx:'running',__proto__:'SECRET'},readyToSwitch:true,token:'SECRET_TOKEN'});
ok(!JSON.stringify(malicious).includes('SECRET'),'raw unknown fields removed');
ok(!malicious.readiness.canSwitchPrimary,'malicious claims cannot promote');
ok(malicious.serviceStates.mysqld==='not_observed','unknown uppercase service invalid');
ok(!malicious.paths.some(p=>'path' in p||'password' in p),'no absolute paths');
ok(Object.keys(malicious.serviceStates).length>0&&Object.keys(malicious.serviceStates).every(x=>typeof x==='string'),'allowlisted services');
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'mhc-writer-audit-'));
try{
 const home=path.join(temp,'home'),prefix=path.join(temp,'prefix');
 fs.mkdirSync(path.join(home,'.config/mhc-full-installer/static'),{recursive:true});
 fs.mkdirSync(path.join(home,'websites/a-site'),{recursive:true});
 fs.mkdirSync(path.join(home,'android-hosting-panel/src'),{recursive:true});
 fs.mkdirSync(path.join(prefix,'etc/nginx'),{recursive:true});
 fs.writeFileSync(path.join(home,'.config/mhc-full-installer/static','demo.conf'),'PASSWORD=ABSOLUTELY_SECRET');
 fs.writeFileSync(path.join(home,'android-hosting-panel/src/server.mjs'),'SECRET_VALUE');
 fs.writeFileSync(path.join(prefix,'etc/nginx/nginx.conf'),'SECRET_PASS');
 const signal=observeLocalSignals(home,prefix);
 ok(signal.siteRegistration,'registration detected without parsing');
 ok(signal.wpRoots,'site root detected');
 ok(signal.panelSource,'panel source metadata');
 ok(signal.nginxConfig,'nginx config metadata');
 const sanitized=JSON.stringify(analyzeWritePaths({signals:signal}));
 ok(!sanitized.includes('ABSOLUTELY_SECRET')&&!sanitized.includes('SECRET_VALUE'),'file contents not exposed');
 ok(!sanitized.includes(temp),'raw paths not exposed');
 fs.unlinkSync(path.join(home,'.config/mhc-full-installer/static/demo.conf'));
 fs.symlinkSync('/dev/null',path.join(home,'.config/mhc-full-installer/static/demo.conf'));
 ok(!observeLocalSignals(home,prefix).siteRegistration,'symlink registration rejected');
 fs.writeFileSync(path.join(home,'.config/mhc-full-installer/static/.env'),'SECRET');
 ok(!observeLocalSignals(home,prefix).siteRegistration,'dotfile not registered');
 const plan=JSON.parse(execFileSync(process.execPath,[path.join(root,'bin/writer-path-audit.mjs'),'plan'],{encoding:'utf8'}));
 ok(plan.writeSideEffects===false&&plan.queriesMariaDB===false&&plan.canSwitchPrimary===false,'plan safe');
 const scanned=JSON.parse(execFileSync(process.execPath,[path.join(root,'bin/writer-path-audit.mjs'),'scan'],{encoding:'utf8',env:{...process.env,HOME:home,PREFIX:prefix}}));
 ok(scanned.pathCount===12&&!scanned.readiness.canSwitchPrimary,'runtime safe');
 ok(scanned.serviceStates.nginx==='not_observed','absent runit fail closed');
 ok(scanned.release===RELEASE,'current version');
}finally{fs.rmSync(temp,{recursive:true,force:true});}
for(const surface of SURFACES){ok(!!item(base,surface.id),'surface exposed');}
console.log(`PASS: writer path read-only inventory, redaction, fail-closed checks (${n} assertions)`);
